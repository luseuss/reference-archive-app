// 이미지 파일을 저장하고 불러오는 "약속"만 적어둔 파일입니다. 실제 동작은 없습니다.
//
// ── 왜 약속을 따로 두나 ──
// 실제 구현(local_image_storage.dart)은 "이 기기의 앱 데이터 폴더가 어디인지"를
// 운영체제에 물어봐야 합니다. 그런데 그건 **플러그인**이라 테스트 환경에서는
// 대답해줄 상대가 없어서 영원히 기다리게 됩니다.
//
// 그래서 화면은 이 약속만 알게 하고, 테스트에서는 즉시 대답하는 가짜를
// 대신 끼워 넣습니다. 저장소(repositories/)를 약속과 구현으로 나눈 것과 같은 이유이고,
// 같은 방식입니다.

import 'dart:typed_data';

/// 이미지 파일을 다루는 방법에 대한 약속입니다.
abstract class ImageStorage {
  /// 파일 이름만 알 때 그 파일의 전체 경로를 만들어 돌려줍니다.
  ///
  /// 데이터베이스에는 이름만 저장되어 있으므로(설계 원칙 4-4),
  /// 화면에서 이미지를 띄우려면 이 함수로 실제 경로를 얻어야 합니다.
  Future<String> getFullPath(String fileName);

  /// 원본 이미지 데이터를 받아서 크기를 줄인 뒤 저장하고, 저장된 파일 이름을 돌려줍니다.
  ///
  /// 돌려주는 값은 "a1b2c3....jpg" 같은 **이름만**입니다.
  /// 이 값을 그대로 ReferenceItem.fileName에 넣으면 됩니다.
  ///
  /// 그림 파일이 아니거나 깨진 파일이면 null을 돌려줍니다.
  Future<String?> saveImage(Uint8List originalBytes);

  /// 저장된 이미지 파일을 실제로 지웁니다.
  ///
  /// 주의: 레퍼런스를 지울 때는 이 함수를 부르지 않습니다.
  /// 레퍼런스 삭제는 소프트 삭제(되살릴 수 있음)라, 파일까지 지워버리면
  /// 되살렸을 때 그림이 사라진 빈 껍데기가 됩니다.
  /// 안 쓰는 파일을 실제로 정리하는 기능은 나중에 따로 만듭니다.
  Future<void> deleteImageFile(String fileName);
}
