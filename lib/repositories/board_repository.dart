// 무드보드를 읽고 쓰는 "약속"만 적어둔 파일입니다. 실제 동작은 들어있지 않습니다.
//
// 왜 약속(abstract class)을 따로 두는지는 reference_repository.dart 맨 위 설명을 보세요.
// 같은 이유입니다.

import '../models/board.dart';

/// 무드보드와 그 위의 카드 배치를 읽고 쓰는 방법에 대한 약속입니다.
///
/// 판(Board)과 카드(BoardCard)를 저장소 하나로 함께 다룹니다. 둘을 따로 나누면
/// "판을 지울 때 그 위의 카드도 함께 정리한다" 같은 일을 화면 쪽에서 두 저장소를
/// 번갈아 부르며 해야 하는데, 그러다 중간에 실패하면 **주인 없는 카드**가 남습니다.
abstract class BoardRepository {
  /// 살아있는 무드보드를 전부 가져옵니다.
  ///
  /// 최근에 고친 것이 앞에 옵니다. 작업 중인 판을 매번 찾아 내려가지 않아도 됩니다.
  Future<List<Board>> getAllBoards();

  /// id로 무드보드 하나를 찾습니다. 없거나 지워졌으면 null입니다.
  Future<Board?> getBoardById(String id);

  /// 무드보드를 저장합니다. 없으면 새로 만들고, 있으면 덮어씁니다.
  ///
  /// updatedAt은 이 함수 안에서 알아서 갱신합니다.
  Future<void> saveBoard(Board board);

  /// 무드보드를 지웁니다(소프트 삭제).
  ///
  /// **그 판 위의 카드 배치도 함께 지웁니다.** 안 그러면 이미 없는 판에 속한
  /// 카드가 데이터베이스에 계속 쌓입니다.
  ///
  /// 판을 지워도 **레퍼런스 자체는 그대로입니다.** 무드보드는 "어디에 놓였는지"만
  /// 기억하는 곳이고, 사진은 목록에 그대로 남아 있습니다.
  Future<void> deleteBoard(String id);

  /// 판 위에 놓인 카드를 전부 가져옵니다.
  ///
  /// 아래에 깔린 것부터(zOrder 작은 것부터) 순서대로 돌려줍니다.
  /// 화면이 이 순서대로 겹쳐 그리면 큰 값이 위에 오게 됩니다.
  Future<List<BoardCard>> getCards(String boardId);

  /// 판마다 카드가 몇 장 올라가 있는지 세어 돌려줍니다. (판 번호 → 장수)
  ///
  /// 목록 화면에서 판마다 하나씩 물어보면 판이 열 개일 때 데이터베이스에
  /// 열 번 오갑니다. 여기서 **한 번에 세어** 돌려줍니다.
  ///
  /// 카드가 하나도 없는 판은 이 표에 아예 안 들어있습니다. 읽는 쪽에서
  /// "없으면 0장"으로 다루면 됩니다.
  Future<Map<String, int>> countCardsByBoard();

  /// 판에 카드 여러 장을 한꺼번에 올립니다.
  ///
  /// 한 장씩 올리는 함수를 따로 두지 않은 이유는 reference_repository.dart의
  /// "여러 건을 한꺼번에" 설명과 같습니다. 무드보드는 보통 한 번에 여러 장을
  /// 올리기 때문에 이쪽이 기본입니다.
  Future<void> addCards(List<BoardCard> cards);

  /// 카드 한 장의 배치(위치·크기·순서)를 저장합니다.
  ///
  /// 카드를 끌어다 놓았을 때 부릅니다. **끄는 도중이 아니라 손을 뗐을 때** 부르세요.
  /// 끄는 동안 매 순간 저장하면 1초에 수십 번 데이터베이스에 쓰게 되어 버벅입니다.
  Future<void> saveCard(BoardCard card);

  /// 카드 여러 장의 배치를 한꺼번에 저장합니다.
  ///
  /// 여러 장을 함께 선택해서 끌었을 때 씁니다(5단계 마퀴 다중선택). 한 장씩
  /// saveCard를 부르면 20장을 옮겼을 때 데이터베이스에 20번 오갑니다.
  /// addCards와 같은 이유로 한꺼번에 보냅니다.
  Future<void> saveCards(List<BoardCard> cards);

  /// 카드를 판에서 내립니다(소프트 삭제).
  ///
  /// **레퍼런스를 지우는 것이 아닙니다.** 판에서만 내려가고 목록에는 그대로 남습니다.
  Future<void> removeCard(String cardId);
}
