// 새 항목의 고유 번호(UUID)를 만드는 곳입니다.
//
// 왜 따로 파일까지 만드나: id를 만드는 방법이 코드 곳곳에 흩어져 있으면
// 나중에 방식을 바꿀 때 전부 찾아 고쳐야 합니다. 한 곳으로 모아둡니다.

import 'package:uuid/uuid.dart';

// Uuid 객체를 매번 새로 만들지 않고 하나만 만들어 재사용합니다.
const Uuid _uuid = Uuid();

/// 새 항목에 쓸 고유 번호를 만들어 돌려줍니다.
///
/// v4는 "완전 무작위" 방식입니다. 순번(1, 2, 3...)을 쓰지 않는 이유는
/// 두 기기에서 각각 만든 3번이 나중에 충돌하기 때문입니다(CLAUDE.md 설계 원칙 1).
/// 무작위라서 서로 다른 기기가 같은 번호를 만들 걱정이 사실상 없습니다.
String newId() {
  return _uuid.v4();
}
