// 앱에서 쓰는 크기 값들을 한곳에 모아둔 파일입니다.
// 모서리 둥글기, 여백, 간격처럼 **숫자로 된 생김새**가 여기 있습니다.
//
// ── 왜 모아두나 ──
// 이 숫자들을 화면마다 흩어 적으면, 나중에 "버튼 모서리를 조금 더 둥글게"
// 같은 요청이 왔을 때 **어디를 다 고쳐야 하는지 알 수 없게** 됩니다.
// 몇 군데 고치고 몇 군데는 놓쳐서 화면마다 미묘하게 다른 상태가 됩니다.
//
// 값들은 기존 웹앱(`app.html`)의 CSS에서 그대로 가져왔습니다.
// 색은 app_palette.dart, 글자는 app_text.dart에 따로 있습니다.

/// 카드·대화상자의 모서리 둥글기입니다. (웹앱의 `--radius: 14px`)
const double appCornerRadius = 14;

/// 버튼의 모서리 둥글기입니다. (웹앱의 `button { border-radius: 9px }`)
const double buttonCornerRadius = 9;

/// 입력창과 드롭다운의 모서리 둥글기입니다.
const double inputCornerRadius = 10;

/// 태그처럼 작은 표시의 모서리 둥글기입니다.
const double tagCornerRadius = 6;

// 완전히 둥근 알약 모양(웹앱의 border-radius: 99px)에는 숫자를 쓰지 않습니다.
// Flutter에는 StadiumBorder()가 있어서 높이에 맞춰 알아서 둥글게 해줍니다.
// 큰 숫자를 넣는 웹 방식보다 정확하고, 글자 크기가 바뀌어도 따라옵니다.

/// 버튼 안쪽 여백입니다. (웹앱의 `padding: 9px 14px`)
const double buttonPaddingHorizontal = 14;
const double buttonPaddingVertical = 9;

/// 입력창 안쪽 여백입니다. (웹앱의 `padding: 10px 14px`)
const double inputPaddingHorizontal = 14;
const double inputPaddingVertical = 10;

/// 칩(알약 모양 필터 버튼) 안쪽 여백입니다.
const double chipPaddingHorizontal = 12;
const double chipPaddingVertical = 5;

/// 화면 가장자리 여백입니다. (웹앱의 `.layout { padding: 20px 24px }`)
const double screenPaddingHorizontal = 24;
const double screenPaddingVertical = 20;

/// 격자 칸 하나의 최대 너비입니다.
///
/// 기존 웹앱은 1240px 화면에서 4칸이었습니다. 이 값이면 얼추 같아집니다.
const double gridMaxCrossAxisExtent = 300;

/// 격자 칸 사이의 간격입니다. (웹앱의 `column-gap: 16px`)
const double gridSpacing = 16;

// ── 무드보드(4단계) ──

/// 카드를 놓을 수 있는 **가장 작은 자리**입니다. (가로)
///
/// ── 판에 끝이 없습니다 (4단계 3번에서 바뀐 것) ──
/// 전에는 판이 1920×1200으로 정해져 있었습니다. "끝이 없으면 카드를 한참
/// 옮겨두고 다시 못 찾는다"는 걱정 때문이었는데, **⛶ 버튼이 카드 전부를
/// 담도록 화면을 맞춰주기 때문에** 그 걱정이 없어졌습니다. 올려둔 카드는
/// 언제나 ⛶ 한 번으로 다시 찾을 수 있습니다.
///
/// 지금은 **오른쪽·아래로 끝이 없습니다.** 대신 왼쪽 위 모서리(0, 0)는
/// 고정입니다. 카드는 0보다 작은 자리로 갈 수 없습니다.
///
/// ── 왜 왼쪽 위만 고정인가 (사방으로 무한하지 않고) ──
/// 음수 자리를 허용하면 **클릭이 안 닿습니다.** Flutter는 상자 바깥의
/// 클릭을 자식에게 내려보내지 않습니다. PR #18에서 카드가 판 아래로
/// 삐져나갔을 때 손잡이가 보이는데도 안 눌렸던 것과 같은 문제입니다.
///
/// 쓸 때 아쉬울 것은 없습니다. 오른쪽·아래로 끝이 없으니 자리가 모자랄
/// 일이 없고, 왼쪽 위로 못 가는 것은 그쪽에 빈 공간이 안 생긴다는 뜻뿐입니다.
///
/// 이 값은 **카드가 몇 장 없을 때도 판이 너무 좁아 보이지 않게** 하는
/// 최소치입니다. 카드가 이보다 넓게 퍼지면 그만큼 따라 늘어납니다.
const double minCanvasWidth = 1920;

/// 카드를 놓을 수 있는 가장 작은 자리입니다. (세로)
const double minCanvasHeight = 1200;

/// 카드가 놓인 범위 바깥에 더 두는 여유입니다.
///
/// 카드를 맨 오른쪽 끝까지 끌었을 때 더 밀 자리가 없으면 답답합니다.
/// 언제나 이만큼은 더 갈 수 있게 남겨둡니다.
const double canvasBreathingRoom = 600;

/// 판에 새로 올린 카드들을 늘어놓을 때 쓰는 간격입니다.
const double boardPlacementSpacing = 20;

/// 판에 새로 올린 카드가 시작하는 자리입니다. 왼쪽 위 모서리에서 띄웁니다.
const double boardPlacementMargin = 40;

/// 새 카드를 늘어놓을 때 **한 줄에 몇 장까지 놓을지**를 정하는 폭입니다.
///
/// 판의 크기가 아닙니다(판에는 끝이 없습니다). 새로 담은 카드를 가로로
/// 늘어놓다가 어디서 다음 줄로 넘어갈지만 정합니다.
const double boardPlacementRowWidth = 1920;

/// 판을 축소할 수 있는 **가장 작은 배율**입니다.
///
/// 전에는 "판 전체가 보이는 배율"이 최소치였습니다. 이제 판에 끝이 없어서
/// 그런 기준을 만들 수 없으므로 숫자로 정해둡니다.
///
/// 0.1 = 10%. 여기까지 줄이면 아주 널찍하게 늘어놓은 것도 한눈에 들어옵니다.
/// 더 줄여도 그림이 점처럼 보일 뿐이라 알아볼 수가 없습니다.
/// 길을 잃었을 때 돌아오는 것은 축소가 아니라 **⛶ 버튼**입니다.
const double minBoardScale = 0.1;

/// 판을 확대할 수 있는 최대 배율입니다.
///
/// 더 키울 수도 있지만, 원본보다 3배 넘게 늘리면 그림이 뭉개져서
/// 확대한 보람이 없습니다.
const double maxBoardScale = 3.0;

/// 확대·축소 버튼을 한 번 누를 때 바뀌는 비율입니다.
///
/// 1.25 = 한 번에 25%씩. 2배씩 뛰면 원하는 크기를 지나쳐서 왔다 갔다 하게 되고,
/// 1.1처럼 잘면 여러 번 눌러야 합니다.
const double boardZoomStep = 1.25;

/// ⛶(카드 전부 보기)로 맞출 때 가장자리에 남기는 여백입니다.
///
/// 카드가 화면 끝에 딱 붙으면 답답하고, 카드 테두리가 잘린 것처럼 보입니다.
///
/// ── 왜 80인가 (아무 숫자가 아닙니다) ──
/// 판 아래쪽에는 선택 툴바(board_selection_bar.dart)가 떠 있습니다.
/// 이 여백이 그 툴바의 높이(약 56)와 바닥에서 띄운 만큼(16)을 합친 것보다
/// 작으면, 카드를 화면 가득 채울 만큼 키운 뒤 ⛶를 누르면 **카드 모서리가
/// 툴바 밑에 깔려서 손잡이를 다시 못 잡는** 일이 생깁니다(실제로 테스트가
/// 이렇게 잡았습니다 — 그룹화 버튼 두 개가 늘어 툴바가 넓어지면서 카드
/// 오른쪽 아래 손잡이와 정확히 겹쳤습니다). 40으로는 부족해서 80으로
/// 올렸습니다.
const double fitAllPadding = 80;

/// 판을 옮길 때 카드 범위가 화면에 **최소한 남아 있어야 하는 크기**입니다.
///
/// 판에 끝이 없어서 아무 데로나 옮길 수 있는데, 그대로 두면 카드가 하나도
/// 안 보이는 빈 곳까지 가서 "내 사진 어디 갔지"가 됩니다. 이만큼은 언제나
/// 화면에 걸쳐 있게 붙잡아둡니다.
const double canvasKeepVisible = 80;

/// 스냅이 걸리는 거리입니다. (판 좌표 기준)
///
/// 이 거리 안까지 들어오면 착 붙습니다. 너무 크면 원하는 자리에 못 놓고
/// 자꾸 끌려가고, 너무 작으면 붙는 느낌이 안 납니다. 기존 웹앱에서
/// 쓰던 값 그대로입니다.
const double boardSnapThreshold = 8;

/// 격자 스냅의 눈금 간격입니다.
///
/// 격자는 **보이지 않습니다.** 붙기만 합니다. 기존 웹앱도 그랬습니다.
const double boardGridSize = 20;

/// 스냅할 때 **이웃으로 쳐주는 거리**입니다. (판 좌표)
///
/// ── 왜 거리 제한이 필요한가 ──
/// 제한이 없으면 3000픽셀 떨어진 카드가 **바로 옆 카드를 이깁니다.** 숫자만
/// 보면 더 가깝기 때문입니다. 사용자 눈에는 "왜 옆에 있는 걸 무시하지?"로
/// 보입니다. 실제로 그 문제로 고쳤습니다.
///
/// 카드가 늘수록 심해집니다. 제한이 없으면 카드 40장일 때 아무 자리에서나
/// **57%** 확률로 붙었습니다. 400으로 제한하니 38%로 떨어집니다.
///
/// 400인 이유: 카드 두 줄쯤 되는 거리입니다. 위아래 두어 줄까지는 줄을
/// 맞추고 싶고, 그보다 멀면 상관없는 카드입니다.
///
/// **스냅이 너무 잘 붙어서 거슬리면 이 값을 줄이세요.** 반대로 줄 맞추기가
/// 잘 안 되면 늘리세요.
const double boardSnapNeighborRange = 400;
